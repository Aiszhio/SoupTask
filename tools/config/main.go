package main

import (
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

type parameter struct {
	Value any    `yaml:"value"`
	Type  string `yaml:"type"`
}

type values struct {
	RTC map[string]parameter `yaml:"rtc"`
}

type generatedEntry struct {
	goName       string
	envName      string
	kind         string
	defaultValue string
}

var keyPattern = regexp.MustCompile(`^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	data, err := os.ReadFile("deploy/k8s/values.yaml")
	if err != nil {
		return err
	}

	var v values
	if err := yaml.Unmarshal(data, &v); err != nil {
		return fmt.Errorf("parse values.yaml: %w", err)
	}
	if len(v.RTC) == 0 {
		return fmt.Errorf("rtc must contain at least one parameter")
	}

	keys := make([]string, 0, len(v.RTC))
	for key := range v.RTC {
		keys = append(keys, key)
	}
	sort.Strings(keys)

	entries := make([]generatedEntry, 0, len(keys))
	usedNames := make(map[string]bool)

	for _, key := range keys {
		if !keyPattern.MatchString(key) {
			return fmt.Errorf("invalid rtc key %q: use snake_case", key)
		}

		goName := toGoName(key)
		if usedNames[goName] {
			return fmt.Errorf("multiple rtc keys generate Go name %q", goName)
		}
		usedNames[goName] = true

		kind, defaultValue, err := parseParameter(key, v.RTC[key])
		if err != nil {
			return err
		}

		entries = append(entries, generatedEntry{
			goName:       goName,
			envName:      strings.ToUpper(key),
			kind:         kind,
			defaultValue: defaultValue,
		})
	}

	var source strings.Builder
	source.WriteString(configPreamble)
	fmt.Fprintln(&source, "const (")
	for _, entry := range entries {
		fmt.Fprintf(
			&source,
			"\t%s Key = %q\n",
			entry.goName,
			entry.envName,
		)
	}
	fmt.Fprintln(&source, ")")
	fmt.Fprintln(&source)
	fmt.Fprintln(&source, "var definitions = map[Key]definition{")
	for _, entry := range entries {
		fmt.Fprintf(
			&source,
			"\t%s: {kind: %s, fallback: %q},\n",
			entry.goName,
			entry.kind,
			entry.defaultValue,
		)
	}
	fmt.Fprintln(&source, "}")

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return fmt.Errorf("format generated Go code: %w", err)
	}

	if err := os.MkdirAll("config", 0755); err != nil {
		return err
	}
	if err := os.WriteFile("config/config.go", formatted, 0644); err != nil {
		return err
	}
	return nil
}

func parseParameter(key string, p parameter) (kind, defaultValue string, err error) {
	switch p.Type {
	case "int":
		value, ok := p.Value.(int)
		if !ok {
			return "", "", fmt.Errorf("rtc.%s.value must be an int", key)
		}
		return "kindInt", strconv.Itoa(value), nil

	case "string":
		value, ok := p.Value.(string)
		if !ok {
			return "", "", fmt.Errorf("rtc.%s.value must be a string", key)
		}
		return "kindString", value, nil

	case "bool":
		value, ok := p.Value.(bool)
		if !ok {
			return "", "", fmt.Errorf("rtc.%s.value must be a bool", key)
		}
		return "kindBool", strconv.FormatBool(value), nil

	default:
		return "", "", fmt.Errorf(
			"rtc.%s.type must be int, string or bool; got %q",
			key,
			p.Type,
		)
	}
}

func toGoName(key string) string {
	parts := strings.Split(key, "_")
	for i, part := range parts {
		parts[i] = strings.ToUpper(part[:1]) + part[1:]
	}
	return strings.Join(parts, "")
}

const configPreamble = `// Code generated by make generate-config; DO NOT EDIT.

package config

import (
	"fmt"
	"os"
	"strconv"
)

type Key string
type valueKind string

const (
	kindInt    valueKind = "int"
	kindString valueKind = "string"
	kindBool   valueKind = "bool"
)

type definition struct {
	kind     valueKind
	fallback string
}

type Value struct {
	key Key
	def definition
	raw string
	err error
}

func Get(key Key) Value {
	def, exists := definitions[key]
	if !exists {
		return Value{err: fmt.Errorf("unknown RTC key %q", key)}
	}

	raw := def.fallback
	if override, exists := os.LookupEnv(string(key)); exists {
		raw = override
	}
	return Value{key: key, def: def, raw: raw}
}

func (v Value) Int() (int, error) {
	if err := v.checkType(kindInt); err != nil {
		return 0, err
	}
	result, err := strconv.Atoi(v.raw)
	if err != nil {
		return 0, fmt.Errorf("%s must be an int: %w", v.key, err)
	}
	return result, nil
}

func (v Value) String() (string, error) {
	if err := v.checkType(kindString); err != nil {
		return "", err
	}
	return v.raw, nil
}

func (v Value) Bool() (bool, error) {
	if err := v.checkType(kindBool); err != nil {
		return false, err
	}
	result, err := strconv.ParseBool(v.raw)
	if err != nil {
		return false, fmt.Errorf("%s must be a bool: %w", v.key, err)
	}
	return result, nil
}

func (v Value) checkType(want valueKind) error {
	if v.err != nil {
		return v.err
	}
	if v.def.kind != want {
		return fmt.Errorf("%s has type %s, requested %s", v.key, v.def.kind, want)
	}
	return nil
}

`
